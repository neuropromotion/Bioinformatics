def add_paragraphs(doc, text, bullet_list=None):
    if bullet_list:
        for item in bullet_list:
            p = doc.add_paragraph(item, style="List Bullet")
            for run in p.runs:
                run.font.size = Pt(12)
        return
    for block in text.split("\n"):
        block = block.strip()
        if not block:
            continue
        p = doc.add_paragraph(block)
        for run in p.runs:
            run.font.size = Pt(12)


